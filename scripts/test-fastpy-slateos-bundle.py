def test_the_tree_holds_what_the_image_needs_and_nothing_else():
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        fastpy, pkg, out = fake_fastpy(root), fake_llvmlite(root), root / "out"
        bundle.build(fastpy, pkg, out, "9.99", fake_toolchain())
        check("the files, exactly", files_under(out), [
            "bin/fastpy",
            "usr/lib/fastpy/BUNDLE",
            "usr/lib/fastpy/compiler/__init__.py",
            "usr/lib/fastpy/compiler/__main__.py",
            "usr/lib/fastpy/compiler/codegen.py",
            "usr/lib/fastpy/llvmlite/__init__.py",
            "usr/lib/fastpy/llvmlite/_version.py",
            "usr/lib/fastpy/llvmlite/ir/__init__.py",
            "usr/lib/fastpy/llvmlite/ir/types.py",
            "usr/lib/fastpy/llvmlite/utils.py",
            "usr/lib/x86_64-slateos/libfastpy_rt.a",
        ])
        check("the archive is the toolchain's",
              (out / "usr/lib/x86_64-slateos/libfastpy_rt.a").read_bytes(), FAKE_ARCHIVE)
        check("the sources are copied byte for byte",
              (out / "usr/lib/fastpy/compiler/codegen.py").read_bytes(),
              (fastpy / "compiler" / "codegen.py").read_bytes())
        check("the command is the launcher",
              (out / "bin/fastpy").read_bytes(), bundle.LAUNCHER.encode("ascii"))


def test_bundle_records_what_the_tree_was_built_from():
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        fastpy, pkg, out = fake_fastpy(root, "0.3.0"), fake_llvmlite(root, "0.47.0"), root / "out"
        bundle.build(fastpy, pkg, out, "9.99", fake_toolchain())
        fields = dict(
            line.split(": ", 1)
            for line in (out / "usr/lib/fastpy/BUNDLE").read_text(encoding="utf-8").splitlines()
        )
        check("the fields, in order", list(fields), [
            "fastpy", "fastpy-version", "llvmlite", "python", "pyc", "libfastpy_rt.a",
        ])
        check("a directory that is no checkout is `unknown`", fields["fastpy"], "unknown")
        check("fastpy's version is pyproject's", fields["fastpy-version"], "0.3.0")
        check("llvmlite's version is _version.py's", fields["llvmlite"], "0.47.0")
        check("the target Python is recorded", fields["python"], "9.99")
        check("the archive is identified by its hash",
              fields["libfastpy_rt.a"], hashlib.sha256(FAKE_ARCHIVE).hexdigest())


def test_pycs_are_written_for_the_running_python_and_said_missing_otherwise():
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        fastpy, pkg = fake_fastpy(root), fake_llvmlite(root)
        out = root / "out"
        said = bundle.build(fastpy, pkg, out, RUNNING, fake_toolchain())
        tag = sys.implementation.cache_tag
        check("this interpreter compiled them", said.startswith("byte-compiled"), True)
        check("every source has its pyc",
              sorted(p.name for p in out.rglob(f"*.{tag}.pyc")),
              sorted(f"{p.stem}.{tag}.pyc" for p in (out / "usr/lib/fastpy").rglob("*.py")))
        pyc = out / "usr/lib/fastpy/compiler/__pycache__" / f"codegen.{tag}.pyc"
        # PEP 552: the flags word after the magic number; bit 0 set means
        # hash-based, bit 1 set means the hash is checked against the source.
        flags = int.from_bytes(pyc.read_bytes()[4:8], "little")
        check("they are checked-hash pycs, valid without the source's mtime",
              flags, 0b11)

        out2 = root / "out2"
        said = bundle.build(fastpy, pkg, out2, "9.99", fake_toolchain())
        check("with no matching Python the report says so",
              said.startswith("NOT byte-compiled"), True)
        check("and no pyc is written", list(out2.rglob("*.pyc")), [])


def test_a_rerun_replaces_the_tree():
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        fastpy, pkg, out = fake_fastpy(root), fake_llvmlite(root), root / "out"
        bundle.build(fastpy, pkg, out, "9.99", fake_toolchain())
        stale = write(out / "usr/lib/fastpy/compiler/removed_upstream.py", "gone\n")
        bundle.build(fastpy, pkg, out, "9.99", fake_toolchain())
        check("a file the new tree lacks does not survive into it", stale.exists(), False)


def test_a_directory_it_did_not_make_is_left_alone():
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        fastpy, pkg, out = fake_fastpy(root), fake_llvmlite(root), root / "out"
        precious = write(out / "notes.txt", "mine\n")
        err = raises(bundle.build, fastpy, pkg, out, "9.99", fake_toolchain())
        check("a non-empty directory without BUNDLE is refused",
              err is not None and "left alone" in err, True)
        check("and its contents are untouched", precious.read_bytes(), b"mine\n")

        empty = root / "empty"
        empty.mkdir()
        bundle.build(fastpy, pkg, empty, "9.99", fake_toolchain())
        check("an empty directory is used", (empty / "usr/lib/fastpy/BUNDLE").is_file(), True)


def test_the_launcher_runs_the_installed_compiler():
    text = bundle.LAUNCHER
    check("its first line names the image's interpreter",
          text.splitlines()[0], "#!/bin/python3")
    check("it puts the installed compiler first on the path",
          'sys.path.insert(0, "/usr/lib/fastpy")' in text, True)
    check("it is ASCII, as a #! line must be readable before any decoding",
          text.isascii(), True)
    compile(text, "fastpy", "exec")  # raises -- and fails the suite -- if not Python
    check("it is Python", True, True)


def test_main_reports_a_failure_in_one_line_and_exits_1():
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        missing = root / "no-fastpy"
        missing.mkdir()
        saved_err = sys.stderr
        sys.stderr = captured = io.StringIO()
        try:
            rc = bundle.main(["--fastpy", str(missing), "--out", str(root / "out")])
        finally:
            sys.stderr = saved_err
        check("a missing checkout exits 1", rc, 1)
        check("with one line naming the problem",
              captured.getvalue().count("\n") == 1
              and captured.getvalue().startswith("fastpy-bundle: "), True)


def main() -> int:
    """Auto-discover `test_*`. The floor is there because a suite that finds
    no tests prints nothing and exits 0, which reads as a pass."""
    tests = [(name, fn) for name, fn in list(globals().items())
             if name.startswith("test_") and callable(fn)]
    if len(tests) < 12:
        print(f"FATAL: found only {len(tests)} tests; the suite has 12. "
              "Discovery is broken, not the code.")
        return 1
    for _, fn in sorted(tests):
        if inspect.signature(fn).parameters:
            print(f"FATAL: {fn.__name__} takes arguments; the runner passes none")
            return 1
        fn()
    print()
    if _FAILURES:
        print(f"{len(_FAILURES)} FAILED: {', '.join(_FAILURES)}")
        return 1
    print(f"all {len(tests)} fastpy-slateos-bundle test groups passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
