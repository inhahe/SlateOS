//! `output.c`'s tables: the format specifiers, the macros made of them, the
//! AIX descriptors and BSD's one-letter sort keys.
//!
//! The tables below are generated from procps-ng 4.0.4's `src/ps/output.c`
//! -- the specifier, its default header, its print function, its sort key,
//! width, vendor and flags, exactly as upstream lists them -- because 275
//! hand-copied rows are 275 chances to mistype one. Both `FORMATS` and
//! `MACROS` are in `strcmp` order, which upstream's `bsearch` relies on; a
//! test here checks it.

