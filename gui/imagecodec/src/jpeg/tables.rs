//! The tables a JPEG decoder keeps from one datastream to the next.
//!
//! libjpeg allocates quantisation and Huffman tables in its permanent pool:
//! `jpeg_abort` and a fresh `jpeg_read_header` leave them as they were, so an
//! "abbreviated" datastream -- one that defines no tables of its own -- is
//! decoded with whatever the last datastream read through the same object
//! defined. TIFF depends on this: its `JPEGTables` field is a datastream of
//! tables alone, read once, and every strip after it is abbreviated. And a
//! strip that does redefine a table leaves the new one in place for the strips
//! after it. [`Tables`] is that permanent state; everything else is per
//! datastream and lives with the decode.

/// `jpeg_natural_order`: where the `i`th coefficient in zig-zag order sits in
/// the block, with sixteen extra entries of 63 so that a run length in a
/// corrupt scan that carries `k` past the end stores into the last
/// coefficient rather than anywhere else -- which libjpeg's decoders do.
pub(super) const NATURAL: [usize; 80] = [
    0, 1, 8, 16, 9, 2, 3, 10, 17, 24, 32, 25, 18, 11, 4, 5, 12, 19, 26, 33, 40, 48, 41, 34, 27, 20,
    13, 6, 7, 14, 21, 28, 35, 42, 49, 56, 57, 50, 43, 36, 29, 22, 15, 23, 30, 37, 44, 51, 58, 59,
    52, 45, 38, 31, 39, 46, 53, 60, 61, 54, 47, 55, 62, 63, 63, 63, 63, 63, 63, 63, 63, 63, 63, 63,
    63, 63, 63, 63, 63, 63,
];

/// `jpeg_natural_order[k]`, for any `k`.
pub(super) fn natural(k: usize) -> usize {
    NATURAL.get(k).copied().unwrap_or(63)
}

/// A Huffman table as `DHT` defines it (`JHUFF_TBL`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub(super) struct HuffSpec {
    /// `bits[l]`: how many codes are `l` bits long; `bits[0]` is unused.
    pub(super) bits: [u8; 17],
    /// The symbols, in code order; zero past the last.
    pub(super) values: [u8; 256],
}

/// The quantisation and Huffman tables, persistent across datastreams.
#[derive(Debug, Clone, Default)]
pub(crate) struct Tables {
    /// `quant_tbl_ptrs`, each in natural order.
    pub(super) quant: [Option<[u16; 64]>; 4],
    /// `dc_huff_tbl_ptrs`.
    pub(super) dc: [Option<HuffSpec>; 4],
    /// `ac_huff_tbl_ptrs`.
    pub(super) ac: [Option<HuffSpec>; 4],
}

