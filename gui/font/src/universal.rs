/// What the Universal Shaping Engine makes of one character.
///
/// The dense order of the variants is the column order of
/// [`TRANSITIONS`](crate::universal_machine::TRANSITIONS): a row is indexed by
/// `category as usize`, so reordering this enum silently mis-scans every run
/// until the machine is regenerated. `tools/gen_universal_machine.py` takes the
/// order from the same dict `tools/gen_universal_table.py` writes the ranges
/// from, so regenerating both together is enough to keep them in step —
/// `the_machine_has_a_column_for_every_category` is what fails if they drift.
///
/// The number in each doc comment is HarfBuzz's, from
/// `hb-ot-shaper-use-machine.rl`. They are *not* the discriminants: HarfBuzz's
/// run to 56 with thirteen gaps, which would cost thirteen dead columns in
/// every row of the table. They are recorded so that a category read out of a
/// HarfBuzz trace can be found here.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
#[repr(u8)]
pub(crate) enum Category {
    /// `O`, 0. Anything the engine has no rule about — most of Unicode.
    /// Heads a symbol cluster, so it is not simply ignored.
    #[default]
    Other = 0,
    /// `B`, 1. A base: the consonant or independent vowel a cluster is built
    /// on.
    Base = 1,
    /// `N`, 4. A digit, which heads a numeral cluster.
    BaseNum = 2,
    /// `GB`, 5. A generic base — a space, a hyphen, a dotted circle: not a
    /// letter, but something a mark may legitimately be hung on.
    BaseOther = 3,
    /// `CGJ`, 6. A combining grapheme joiner, a ZWJ or a variation selector:
    /// hidden from the cluster machine entirely. See [`clusters`].
    Cgj = 4,
    /// `SUB`, 11. A subjoined consonant written as one character, rather than
    /// as a virama followed by a consonant.
    ConsSub = 5,
    /// `H`, 12. A visible virama, which kills the inherent vowel.
    Halant = 6,
    /// `HN`, 13. A number joiner, which binds two digits into one numeral.
    HalantNum = 7,
    /// `ZWNJ`, 14. Zero-width non-joiner. Hidden from the cluster machine when
    /// what follows it is a combining mark. See [`clusters`].
    NonJoiner = 8,
    /// `WJ`, 16. Word joiner.
    WordJoiner = 9,
    /// `R`, 18. A repha: written first and drawn late. Either the character
    /// said so or the font's `rphf` did — see [`record_rphf`].
    Repha = 10,
    /// `VPre`, 22. A dependent vowel drawn to the left of the cluster, and so
    /// moved to the front of it. See [`reorder_cluster`].
    VowelPre = 11,
    /// `VMPre`, 23. A vowel modifier drawn to the left, moved with the vowels.
    VowelModPre = 12,
    /// `FAbv`, 24. A final consonant drawn above.
    ConsFinalAbove = 13,
    /// `FBlw`, 25. A final consonant drawn below.
    ConsFinalBelow = 14,
    /// `FPst`, 26. A final consonant drawn after.
    ConsFinalPost = 15,
    /// `MAbv`, 27. A medial consonant drawn above.
    ConsMedAbove = 16,
    /// `MBlw`, 28. A medial consonant drawn below.
    ConsMedBelow = 17,
    /// `MPst`, 29. A medial consonant drawn after.
    ConsMedPost = 18,
    /// `MPre`, 30. A medial consonant drawn before.
    ConsMedPre = 19,
    /// `CMAbv`, 31. A consonant modifier drawn above — a nukta and its kin.
    ConsModAbove = 20,
    /// `CMBlw`, 32. A consonant modifier drawn below.
    ConsModBelow = 21,
    /// `VAbv`, 33. A dependent vowel drawn above.
    VowelAbove = 22,
    /// `VBlw`, 34. A dependent vowel drawn below.
    VowelBelow = 23,
    /// `VPst`, 35. A dependent vowel drawn after.
    VowelPost = 24,
    /// `VMAbv`, 37. A vowel modifier drawn above.
    VowelModAbove = 25,
    /// `VMBlw`, 38. A vowel modifier drawn below.
    VowelModBelow = 26,
    /// `VMPst`, 39. A vowel modifier drawn after.
    VowelModPost = 27,
    /// `SMAbv`, 41. A symbol modifier drawn above, which makes a symbol
    /// cluster.
    SymModAbove = 28,
    /// `SMBlw`, 42. A symbol modifier drawn below.
    ///
    /// No character carries it. Upstream's table `#define`s `SMBlw` and then
    /// `#undef`s it without ever having used it, so nothing in `USE_RANGES`
    /// names this variant either. It has to exist regardless: the machine's
    /// columns are these discriminants, and dropping it would shift every
    /// category after it one column left.
    #[allow(dead_code)]
    SymModBelow = 29,
    /// `CS`, 43. A consonant with a stacker built in, which may head a cluster
    /// the way a repha does.
    ConsWithStacker = 30,
    /// `IS`, 44. An invisible stacker: a virama that stacks without being
    /// drawn. Terminates a cluster.
    InvisibleStacker = 31,
    /// `FMAbv`, 45. A final-consonant modifier drawn above.
    ConsFinalModAbove = 32,
    /// `FMBlw`, 46. A final-consonant modifier drawn below.
    ConsFinalModBelow = 33,
    /// `FMPst`, 47. A final-consonant modifier with nowhere in particular to
    /// go. Alone it is a cluster of its own, and one that earns no dotted
    /// circle — the grammar lists it between the well-formed rules and the
    /// broken one for exactly that reason.
    ConsFinalModPost = 34,
    /// `Sk`, 48. A sakot, which joins two Tai Tham syllables and terminates a
    /// cluster.
    Sakot = 35,
    /// `G`, 49. An Egyptian hieroglyph.
    Hieroglyph = 36,
    /// `J`, 50. A hieroglyph joiner.
    HieroglyphJoiner = 37,
    /// `SB`, 51. The start of a hieroglyph segment — a bracket.
    HieroglyphSegBegin = 38,
    /// `SE`, 52. The end of one.
    HieroglyphSegEnd = 39,
    /// `HVM`, 53. A character that is a halant in some contexts and a vowel
    /// modifier in others, which is why the grammar admits it in both places.
    HalantOrVowelModifier = 40,
    /// `HM`, 54. A hieroglyph modifier.
    HieroglyphMod = 41,
    /// `HR`, 55. A hieroglyph mirror control.
    HieroglyphMirror = 42,
    /// `RK`, 56. A reordering killer, which terminates a cluster the way an
    /// invisible stacker does.
    ReorderingKiller = 43,
}

impl Category {
    /// How many there are, which is how wide a row of the machine is.
    pub(crate) const COUNT: usize = 44;

    /// The category of `ch`, or [`Other`](Self::Other) if the table has no
    /// range covering it — which is the answer for all but about fifteen
    /// thousand code points.
    #[must_use]
    pub(crate) fn of(ch: char) -> Self {
        let cp = ch as u32;
        // The ranges are disjoint and sorted, so the last one starting at or
        // before `cp` is the only one that can contain it.
        let Some(i) = USE_RANGES
            .partition_point(|&(lo, _, _)| lo <= cp)
            .checked_sub(1)
        else {
            return Self::Other;
        };
        match USE_RANGES.get(i) {
            Some(&(_, hi, category)) if cp <= hi => category,
            _ => Self::Other,
        }
    }
}

/// Everything the engine needs to know about one character, on the glyph it
/// became.
///
/// Two facts and not one, because the cluster machine asks two questions and
/// only the first has a [`Category`] for an answer. The second — "is the next
/// visible thing a combining mark?" — is the Unicode general category `Mn`,
/// `Mc` or `Me`, and it is *not* recoverable from the USE category: five
/// categories contain both marks and non-marks, `Other` most of all. So the
/// bit rides along. See [`clusters`].
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub(crate) struct Char {
    /// What it is.
    pub(crate) category: Category,
    /// Whether the character was a combining mark of any kind:
    /// `HB_UNICODE_GENERAL_CATEGORY_IS_MARK`, which is
    /// [`norm::is_any_mark`](crate::norm::is_any_mark) and *not*
    /// [`SubGlyph::mark`], whose question is about advance widths and whose
    /// answer is conditional on the face.
    pub(crate) mark: bool,
}

impl Char {
    /// Not USE: what every glyph of every run this shaper does not touch
    /// carries.
    pub(crate) const DEFAULT: Self = Self {
        category: Category::Other,
        mark: false,
    };

    /// What `ch` contributes.
    #[must_use]
    pub(crate) fn of(ch: char) -> Self {
        Self {
            category: Category::of(ch),
            mark: norm::is_any_mark(ch),
        }
    }
}

/// Which of the grammar's ten rules matched a cluster.
///
/// Nine kinds for ten rules: `other` and the lone `FMPst` rule both produce
/// [`NonCluster`](Self::NonCluster), which is HarfBuzz's arrangement and the
/// point of it is that a stray final-consonant modifier gets no dotted circle.
// `NonCluster` repeats the type's name, which the lint dislikes. It is
// upstream's `use_non_cluster` and it is the *negation* of the type, not a
// variant of it — the alternatives ("Lone", "None") both read as "no cluster
// matched" when what happened is that a cluster of exactly this kind did.
#[allow(clippy::enum_variant_names)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Cluster {
    /// Ended by an invisible stacker or a reordering killer.
    ViramaTerminated,
    /// Ended by a sakot, which joins it to the syllable that follows.
    SakotTerminated,
    /// The ordinary case: a base with modifiers, vowels and finals on it.
    Standard,
    /// Digits bound by number joiners, ending in a joiner.
    NumberJoinerTerminated,
    /// Digits bound by number joiners, ending in a digit.
    Numeral,
    /// Something that is not a letter carrying a symbol modifier.
    Symbol,
    /// Egyptian hieroglyphs, which have a grammar of their own and never join.
    Hieroglyph,
    /// Not a well-formed cluster: marks with no base to hang on. The only kind
    /// that earns a dotted circle.
    Broken,
    /// One character of anything else, and the lone `FMPst` rule. Never
    /// reordered, never given a circle, and never joined to.
    NonCluster,
}

impl Cluster {
    /// This kind as the low nibble of a [`SubGlyph::syllable`] byte.
    ///
    /// The numbering is HarfBuzz's `use_syllable_type_t`, so a value read out
    /// of one of its traces means the same thing here — and so that the leading
    /// unstamped glyphs [`clusters`] has to account for read back as the kind
    /// HarfBuzz's zero gives them.
    #[must_use]
    pub(crate) fn code(self) -> u8 {
        match self {
            Self::ViramaTerminated => 0,
            Self::SakotTerminated => 1,
            Self::Standard => 2,
            Self::NumberJoinerTerminated => 3,
            Self::Numeral => 4,
            Self::Symbol => 5,
            Self::Hieroglyph => 6,
            Self::Broken => 7,
            Self::NonCluster => 8,
        }
    }

    /// The kind [`code`](Self::code) writes as `code`'s low nibble.
    ///
    /// The seven nibbles no kind uses read back as
    /// [`NonCluster`](Self::NonCluster), the kind that does nothing.
    #[must_use]
    pub(crate) fn from_code(code: u8) -> Self {
        match code & 0x0F {
            0 => Self::ViramaTerminated,
            1 => Self::SakotTerminated,
            2 => Self::Standard,
            3 => Self::NumberJoinerTerminated,
            4 => Self::Numeral,
            5 => Self::Symbol,
            6 => Self::Hieroglyph,
            7 => Self::Broken,
            _ => Self::NonCluster,
        }
    }
}

