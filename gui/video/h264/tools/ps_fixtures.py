"""Write src/ps/tests/fixtures.rs: real parameter sets, and what FFmpeg reads in them.

For each of a few of FFmpeg's H.264 conformance streams (its FATE suite's
h264-conformance directory) this takes the first sequence and picture
parameter set as they are in the file -- escapes and all -- and every
syntax element FFmpeg's `trace_headers` bitstream filter prints for them,
and writes both out as Rust constants. src/ps/tests.rs parses the bytes and
checks what it reads against the trace.

    python gui/video/h264/tools/ps_fixtures.py <fate-suite>/h264-conformance

`ffmpeg` must be on PATH. The streams are FFmpeg's FATE samples
(rsync://fate-suite.ffmpeg.org/fate-suite/h264-conformance, or over https).
"""
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "src" / "ps" / "tests" / "fixtures.rs"

# (constant name, file, what it exercises)
FIXTURES = [
    ("BASELINE", "BA1_FT_C.264", "Baseline, the simplest stream"),
    ("MBAFF_VUI", "MR9_BT_B.h264", "Main: VUI, POC type 1, MBAFF, CABAC"),
    ("SCALING", "FRext/HPCAQ2LQ_BRCM_B.264", "High: scaling lists in both sets"),
    ("MONOCHROME", "FRext/HPCAMOLQ_BRCM_B.264", "High 4:0:0 with scaling lists"),
    ("SPS_LISTS", "FRext/FRExt1_Panasonic.avc", "High: SPS lists, the PPS falling back to them"),
    ("HIGH422_10", "FRext/PPH422I5_Panasonic_A.264", "High 4:2:2 10-bit, fields, cropped"),
    ("HIGH_VUI", "slice2_field_aurora4.264", "High: VUI with timing, fields"),
    ("CROPPED", "CVFC1_Sony_C.jsv", "Baseline, cropped"),
]


def units(data: bytes):
    """Annex B units as they are in the file: start codes off, trailing zero
    bytes off (they belong to the next start code), escapes kept."""
    starts = []
    i = 0
    while (j := data.find(b"\x00\x00\x01", i)) >= 0:
        starts.append(j + 3)
        i = j + 3
    for k, s in enumerate(starts):
        e = starts[k + 1] - 3 if k + 1 < len(starts) else len(data)
        unit = data[s:e]
        while unit.endswith(b"\x00"):
            unit = unit[:-1]
        yield unit


def first(data: bytes, kind: int) -> bytes:
    for u in units(data):
        if u and u[0] & 0x1F == kind:
            return u
    raise SystemExit(f"no unit of type {kind}")


def trace(path: Path) -> dict:
    """The first SPS's and the first PPS's syntax elements, in order."""
    out = subprocess.run(
        ["ffmpeg", "-hide_banner", "-i", str(path), "-c", "copy", "-bsf:v", "trace_headers",
         "-frames:v", "1", "-f", "null", "-"],
        capture_output=True, text=True, encoding="utf-8", errors="replace", check=False,
    ).stderr
    sets: dict = {}
    section = None
    for line in out.splitlines():
        if "Sequence Parameter Set" in line:
            section = "sps" if "sps" not in sets else None
            if section:
                sets[section] = []
            continue
        if "Picture Parameter Set" in line:
            section = "pps" if "pps" not in sets else None
            if section:
                sets[section] = []
            continue
        if "] " in line and ("Slice" in line or "Packet:" in line or "Extradata" in line
                             or "Supplemental" in line or "Access Unit" in line):
            section = None
            continue
        parts = line.split()
        if section and len(parts) >= 6 and parts[-2] == "=":
            sets[section].append((parts[4], int(parts[-1])))
    return sets


def rust_bytes(b: bytes) -> str:
    rows = [", ".join(f"0x{x:02X}" for x in b[i:i + 12]) for i in range(0, len(b), 12)]
    return "[\n" + "".join(f"        {r},\n" for r in rows) + "    ]"


def rust_fields(fields) -> str:
    return "[\n" + "".join(f'        ("{n}", {v}),\n' for n, v in fields) + "    ]"


def main() -> None:
    root = Path(sys.argv[1])
    body = [
        "// Generated by tools/ps_fixtures.py from FFmpeg's FATE H.264 conformance",
        "// streams, and FFmpeg's trace_headers reading of them. Do not edit.",
        "",
        "/// One stream's first parameter sets, and the trace of each.",
        "pub(super) struct Fixture {",
        "    pub(super) name: &'static str,",
        "    pub(super) sps: &'static [u8],",
        "    pub(super) pps: &'static [u8],",
        "    pub(super) sps_trace: &'static [(&'static str, i64)],",
        "    pub(super) pps_trace: &'static [(&'static str, i64)],",
        "}",
        "",
    ]
    names = []
    for const, file, what in FIXTURES:
        path = root / file
        data = path.read_bytes()
        t = trace(path)
        body += [
            f"/// {file}: {what}.",
            f"pub(super) const {const}: Fixture = Fixture {{",
            f'    name: "{file}",',
            f"    sps: &{rust_bytes(first(data, 7))},",
            f"    pps: &{rust_bytes(first(data, 8))},",
            f"    sps_trace: &{rust_fields(t['sps'])},",
            f"    pps_trace: &{rust_fields(t['pps'])},",
            "};",
            "",
        ]
        names.append(const)
    body += [
        "/// Every fixture.",
        f"pub(super) const ALL: [Fixture; {len(names)}] = [{', '.join(names)}];",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(body), encoding="utf-8", newline="\n")
    # Formatted as `cargo fmt` would, so that regenerating and diffing
    # compares like with like.
    subprocess.run(["rustfmt", "--edition", "2024", str(OUT)], check=True)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
