//! The Universal Shaping Engine.
//!
//! One shaper for eighty-eight scripts — everything from Balinese to Egyptian
//! hieroglyphs — and the last of the five this crate has. Where
//! [`indic_shape`](crate::indic_shape), [`khmer`](crate::khmer) and
//! [`myanmar`](crate::myanmar) each encode one writing system's rules, USE
//! encodes the *shape* those rules share and leaves the particulars to the
//! font: a cluster is a base with modifiers hung on it, the font's features
//! decide what each modifier turns into, and the engine's own contribution is
//! to say where a cluster ends, which glyphs a repha and a pre-base vowel move
//! past, and which of the four positional forms a cluster takes.
//!
//! Microsoft's specification is at
//! <https://learn.microsoft.com/en-us/typography/script-development/use>; this
//! follows HarfBuzz's `hb-ot-shaper-use.cc` and `hb-ot-shaper-use-machine.rl`,
//! which is the implementation everything is measured against.
//!
//! # The three things that make it unlike the other three shapers
//!
//! * **The cluster machine reads a filtered view of the run.** Indic, Khmer and
//!   Myanmar hand their machines every glyph. USE hides two kinds first — the
//!   `CGJ` category, which is the combining grapheme joiner, ZWJ and the
//!   variation selectors, and a ZWNJ whose next visible glyph is a combining
//!   mark — so that neither can cut a cluster in half. The hidden glyphs are
//!   not *removed*: they stay in the run and belong to whichever cluster the
//!   machine was in when it stepped over them. See [`clusters`], which is
//!   where the two consequences of that are written out.
//! * **The font decides what a repha is.** Indic recognises a reph by spelling
//!   (`Ra` + virama) and Myanmar a kinzi likewise. USE runs the font's `rphf`
//!   feature *alone*, as a stage of its own, and then asks which glyph the font
//!   rewrote — see [`record_rphf`]. `pref` is treated the same way, and a glyph
//!   it rewrote becomes a pre-base vowel. Neither question can be answered
//!   without having run the lookup, which is why [`SubGlyph::substituted`]
//!   exists.
//! * **The positional forms are per *cluster*, not per letter.** For most USE
//!   scripts `isol`/`init`/`medi`/`fina` do not mean cursive joining at all:
//!   [`setup_topographical_masks`] hands them out by looking at whether the
//!   *previous cluster* joined, which is a much coarser question than the
//!   Unicode `Joining_Type` that [`joining`](crate::joining) answers. The
//!   eleven USE scripts that really do join cursively are the exception and
//!   take the ordinary path — see [`has_arabic_joining`].
//!
//! # What is not here
//!
//! * **Vowel constraints.** HarfBuzz's `preprocess_text_use` is
//!   `_hb_preprocess_text_vowel_constraints`, which inserts a dotted circle
//!   between a consonant and an independent vowel that Unicode says may not
//!   follow it. That is a table of its own and a separate pass; this crate has
//!   neither, for USE or for Indic.
//! * **`compose_use` as a hook of this shaper's own.** HarfBuzz refuses to
//!   recompose a split matra during normalization by declining any composition
//!   whose first character is a mark, and hangs that refusal off each shaper's
//!   vtable. The rule *is* implemented, but not here: it lives in
//!   [`norm`](crate::norm) as `SplitVowels::LeaveApart`, one switch the drawing
//!   path always sets and the text path never does, rather than a copy per
//!   shaper. It is safe as a global because the 47 characters it can affect all
//!   belong to Indic or USE scripts — `norm`'s
//!   `only_indic_and_use_compose_from_a_mark` is what fails if a table
//!   regeneration changes that. See `design-decisions.md` §439. Khmer's
//!   [`split_matras`](crate::khmer::split_matras) is the same rule for the
//!   decompositions Unicode does *not* record.
//!
//! # The categories and the machine
//!
//! [`Category`] and the ranges it is read from are generated by
//! `tools/gen_universal_table.py` from Unicode and the `ms-use` override files
//! HarfBuzz vendors, and checked against HarfBuzz's own packed table code point
//! by code point. [`Cluster`] and the DFA that produces it are generated by
//! `tools/gen_universal_machine.py` from the ten regular expressions of the
//! ragel grammar. Neither is transcribed by hand, and neither should be edited.

