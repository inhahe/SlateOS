//! The terminfo compiler's tables: generated from the reference's libtinfo
//! (Ubuntu 24.04's ncurses 6.4+20240113) by `scripts/gen-terminfo-captab.py`,
//! which asks the library's own lookups for every name. Not edited by hand:
//! rerun the script.

use crate::Kind;

/// One capability of a name table: its name there, its type, its index
/// among its type's capabilities in `term.h`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Cap {
    /// The name.
    pub name: &'static str,
    /// The type.
    pub kind: Kind,
    /// The index.
    pub index: usize,
}

impl Cap {
    /// A table row -- a call, so that each stays one line.
    #[must_use]
    pub const fn new(name: &'static str, kind: Kind, index: usize) -> Self {
        Self { name, kind, index }
    }
}

/// One alias of a source file's.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Alias {
    /// The name as written.
    pub from: &'static str,
    /// The name it stands for; `None` to drop it.
    pub to: Option<&'static str>,
    /// Whose name it is (`AT&T`, `BSD`...).
    pub source: &'static str,
}

impl Alias {
    /// A table row.
    #[must_use]
    pub const fn new(from: &'static str, to: Option<&'static str>, source: &'static str) -> Self {
        Self { from, to, source }
    }
}

/// One user-definable capability.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct UserCap {
    /// Its name.
    pub name: &'static str,
    /// Its types: a bit for each of `BOOLEAN` (1), `NUMBER` (2), `STRING` (4).
    pub kinds: u8,
    /// How many parameters it takes.
    pub argc: u32,
    /// Which of them are strings, a bit each.
    pub args: u32,
    /// Its index in its own table.
    pub index: usize,
}

impl UserCap {
    /// A table row.
    #[must_use]
    pub const fn new(name: &'static str, kinds: u8, argc: u32, args: u32, index: usize) -> Self {
        Self {
            name,
            kinds,
            argc,
            args,
            index,
        }
    }
}

