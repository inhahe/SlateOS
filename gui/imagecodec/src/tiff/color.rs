//! `YCbCr` and CIE L*a*b* to RGB, as libtiff 4.7.1 converts them
//! (`tif_color.c`).
//!
//! Both are floating-point in libtiff, and ported operation for operation in
//! single precision -- the order of every multiplication and division kept --
//! so that the results agree to the bit. The one call libtiff makes that a
//! `no_std` crate has no copy of, `pow` for the display's gamma, is a table
//! here ([`GAMMA`]), generated with the C library libtiff itself runs on.

/// `TIFFYCbCrToRGB`: the fixed-point tables libtiff converts through.
pub(super) struct YCbCr {
    cr_r: [i32; 256],
    cb_b: [i32; 256],
    cr_g: [i32; 256],
    cb_g: [i32; 256],
    y: [i32; 256],
}

const SHIFT: u32 = 16;
const ONE_HALF: i32 = 1 << (SHIFT - 1);

/// `FIX`: a float to 16.16 fixed point, rounded as the C rounds it (the
/// product is single precision, the half added in double).
#[allow(clippy::cast_possible_truncation)] // In range: at most 2 * 65536.
fn fix(x: f32) -> i32 {
    (f64::from(x * 65536.0) + 0.5) as i32
}

/// `CLAMP`, which sends NaN to the minimum.
fn clamp(f: f32, min: f32, max: f32) -> f32 {
    if f.is_nan() || f < min {
        min
    } else if f > max {
        max
    } else {
        f
    }
}

/// `CLAMPw`.
fn clamp_w(v: f32, min: f32, max: f32) -> f32 {
    if v < min {
        min
    } else if v > max {
        max
    } else {
        v
    }
}

/// `Code2V`: a coded value scaled from the reference black and white to
/// `cr` levels.
#[allow(clippy::cast_possible_truncation, clippy::cast_precision_loss)]
fn code_to_value(c: i32, rb: f32, rw: f32, cr: f32) -> f32 {
    // `(c - (int32_t)RB)`: the black point truncated toward zero first. RB
    // was checked to be well inside `i32` (`in_reference_range`).
    let offset = c.wrapping_sub(rb as i32);
    let span = rw - rb;
    let span = if span != 0.0 { span } else { 1.0 };
    (offset as f32 * cr) / span
}

/// Whether `f` is a reference value libtiff accepts
/// (`isInRefBlackWhiteRange`).
#[allow(clippy::cast_precision_loss)]
pub(super) fn in_reference_range(f: f32) -> bool {
    f > (-0x7FFF_FFFF + 128) as f32 && f < 0x7FFF_FFFF as f32
}

impl YCbCr {
    /// `TIFFYCbCrToRGBInit`, from the luma coefficients and the reference
    /// black and white, already checked (`initYCbCrConversion`).
    #[allow(clippy::cast_possible_truncation)] // `(int32_t)` casts of clamped floats.
    pub(super) fn new(luma: [f32; 3], reference: [f32; 6]) -> Self {
        let [red, green, blue] = luma;
        let f1 = 2.0 - 2.0 * red;
        let d1 = fix(clamp(f1, 0.0, 2.0));
        let f2 = red * f1 / green;
        let d2 = fix(clamp(f2, 0.0, 2.0)).wrapping_neg();
        let f3 = 2.0 - 2.0 * blue;
        let d3 = fix(clamp(f3, 0.0, 2.0));
        let f4 = blue * f3 / green;
        let d4 = fix(clamp(f4, 0.0, 2.0)).wrapping_neg();
        let limit = 128.0 * 32.0;
        let [black, white, cb_black, cb_white, cr_black, cr_white] = reference;
        // For each coded value 0..=255, taken as x = value - 128.
        let x = |i: usize| i32::try_from(i).unwrap_or(0).wrapping_sub(128);
        let cr = |i: usize| {
            clamp_w(
                code_to_value(x(i), cr_black - 128.0, cr_white - 128.0, 127.0),
                -limit,
                limit,
            ) as i32
        };
        let cb = |i: usize| {
            clamp_w(
                code_to_value(x(i), cb_black - 128.0, cb_white - 128.0, 127.0),
                -limit,
                limit,
            ) as i32
        };
        // |d| <= 2 * 65536 and |cr|, |cb| <= 4096: no product overflows.
        Self {
            cr_r: core::array::from_fn(|i| d1.wrapping_mul(cr(i)).wrapping_add(ONE_HALF) >> SHIFT),
            cb_b: core::array::from_fn(|i| d3.wrapping_mul(cb(i)).wrapping_add(ONE_HALF) >> SHIFT),
            cr_g: core::array::from_fn(|i| d2.wrapping_mul(cr(i))),
            cb_g: core::array::from_fn(|i| d4.wrapping_mul(cb(i)).wrapping_add(ONE_HALF)),
            y: core::array::from_fn(|i| {
                clamp_w(
                    code_to_value(x(i).wrapping_add(128), black, white, 255.0),
                    -limit,
                    limit,
                ) as i32
            }),
        }
    }

    /// `TIFFYCbCrtoRGB`: one pixel, 8-bit samples.
    pub(super) fn rgb(&self, y: u32, cb: u32, cr: u32) -> (u32, u32, u32) {
        let at = |table: &[i32; 256], v: u32| table.get(v.min(255) as usize).copied().unwrap_or(0);
        let luma = at(&self.y, y);
        let channel = |v: i32| u32::try_from(v.clamp(0, 255)).unwrap_or(0);
        let r = luma.wrapping_add(at(&self.cr_r, cr));
        let g = luma.wrapping_add(at(&self.cb_g, cb).wrapping_add(at(&self.cr_g, cr)) >> SHIFT);
        let b = luma.wrapping_add(at(&self.cb_b, cb));
        (channel(r), channel(g), channel(b))
    }
}

/// The default luma coefficients (CCIR 601-1).
pub(super) const DEFAULT_LUMA: [f32; 3] = [0.299, 0.587, 0.114];

/// The default reference black and white of `YCbCr` samples.
pub(super) const DEFAULT_YCBCR_REFERENCE: [f32; 6] = [0.0, 255.0, 128.0, 255.0, 128.0, 255.0];

/// CIE D50, the default white point (Adobe's technical note; TIFF 6.0 gives
/// none).
const D50: [f32; 3] = [96.4250, 100.0, 82.4680];

/// The default `WhitePoint`: D50 as chromaticity.
pub(super) const DEFAULT_WHITE_POINT: [f32; 2] = [
    D50[0] / (D50[0] + D50[1] + D50[2]),
    D50[1] / (D50[0] + D50[1] + D50[2]),
];

/// `TIFFCIELabToRGB` for libtiff's built-in sRGB display.
pub(super) struct Lab {
    /// The reference white, X0 Y0 Z0.
    white: [f32; 3],
}

/// `display_sRGB`'s XYZ-to-luminance matrix.
const MATRIX: [f32; 9] = [
    3.2410, -1.5374, -0.4986, -0.9692, 1.8760, 0.0416, 0.0556, -0.2040, 1.0570,
];
/// Luminance for black and for reference white (`d_Y0R`, `d_YCR`: the same
/// for all three channels).
const Y0: f32 = 1.0;
const YC: f32 = 100.0;
const RANGE: usize = 1500;

impl Lab {
    /// `initCIELabConversion`: `None` for a white point libtiff refuses.
    pub(super) fn new(white_point: [f32; 2]) -> Option<Self> {
        let [x, y] = white_point;
        if y == 0.0 {
            return None;
        }
        let reference = 100.0f32;
        Some(Self {
            white: [x / y * reference, reference, (1.0 - x - y) / y * reference],
        })
    }

    /// `TIFFCIELab16ToXYZ` then `TIFFXYZToRGB`: L from 0 to 65535, a and b
    /// in 1/256ths.
    #[allow(clippy::cast_precision_loss)] // As the C converts.
    pub(super) fn rgb16(&self, l: u32, a: i32, b: i32) -> (u32, u32, u32) {
        let [x0, y0, z0] = self.white;
        let l = l as f32 * 100.0 / 65535.0;
        let (y, cby) = if l < 8.856 {
            let y = (l * y0) / 903.292;
            (y, 7.787 * (y / y0) + 16.0 / 116.0)
        } else {
            let cby = (l + 16.0) / 116.0;
            (y0 * cby * cby * cby, cby)
        };
        let side = |t: f32, n0: f32| {
            if t < 0.2069 {
                n0 * (t - 0.13793) / 7.787
            } else {
                n0 * t * t * t
            }
        };
        let x = side(a as f32 / 256.0 / 500.0 + cby, x0);
        let z = side(cby - b as f32 / 256.0 / 200.0, z0);
        let [m0, m1, m2, m3, m4, m5, m6, m7, m8] = MATRIX;
        let yr = m0 * x + m1 * y + m2 * z;
        let yg = m3 * x + m4 * y + m5 * z;
        let yb = m6 * x + m7 * y + m8 * z;
        (level(yr), level(yg), level(yb))
    }

    /// `TIFFCIELabToXYZ`'s 8-bit form: L from 0 to 255, a and b signed.
    pub(super) fn rgb8(&self, l: u32, a: i32, b: i32) -> (u32, u32, u32) {
        self.rgb16(
            l.wrapping_mul(257),
            a.wrapping_mul(256),
            b.wrapping_mul(256),
        )
    }
}

/// One channel's luminance to its 8-bit level, through the display table.
#[allow(
    clippy::cast_possible_truncation,
    clippy::cast_sign_loss,
    clippy::cast_precision_loss
)]
#[allow(clippy::manual_clamp)] // `clamp` keeps a NaN, which `TIFFmax` makes Y0.
fn level(luminance: f32) -> u32 {
    let clipped = luminance.max(Y0).min(YC);
    let step = (YC - Y0) / RANGE as f32;
    // `(size_t)` of a non-negative float: truncation.
    let i = (((clipped - Y0) / step) as usize).min(RANGE);
    let v = f32::from_bits(GAMMA.get(i).copied().unwrap_or(0));
    // `RINT`, in double as the C adds the half.
    let rounded = if v > 0.0 {
        f64::from(v) + 0.5
    } else {
        f64::from(v) - 0.5
    };
    (rounded as u32).min(255)
}

