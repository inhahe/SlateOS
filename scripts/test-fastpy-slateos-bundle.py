#!/usr/bin/env python3
"""Regression tests for `scripts/fastpy-slateos-bundle.py`.

Run: `python scripts/test-fastpy-slateos-bundle.py` (exit 0 = pass, 1 = fail).
No pytest dependency, like the other suites here: this has to run from a bare
checkout, and the boot test runs every `scripts/test-*.py`.

What is tested is the script's own logic -- which files make the tree, where
they go, what is left out, what `BUNDLE` records, when an existing directory
may be cleared -- against a fake fastpy checkout and a fake llvmlite built in
a temporary directory. The real runtime archive is fastpy's to build and test
(`build_slateos_runtime_archive`, in fastpy's own suite): reaching it from
here would cross-compile a C runtime inside every lane's boot test, into a
directory outside this repository that every lane shares. A stand-in
toolchain whose archive builder writes a fixed file takes its place.

In-process throughout, and starting no other process: the fakes are not git
checkouts, so `git_identity` answers without running git, and the
byte-compile is done by this interpreter.
"""

from __future__ import annotations

import hashlib
import importlib.util
import inspect
import io
import os
import sys
import tempfile
import types
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCRIPT = HERE / "fastpy-slateos-bundle.py"

_FAILURES: list[str] = []


def check(label: str, got: object, want: object) -> bool:
    if got == want:
        print(f"PASS  {label}")
        return True
    print(f"FAIL  {label}")
    print(f"        got:  {got!r}")
    print(f"        want: {want!r}")
    _FAILURES.append(label)
    return False


def load():
    spec = importlib.util.spec_from_file_location("fastpy_slateos_bundle_under_test", SCRIPT)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


bundle = load()

#: What the stand-in archive builder writes: an empty `ar` archive.
FAKE_ARCHIVE = b"!<arch>\n"

RUNNING = f"{sys.version_info[0]}.{sys.version_info[1]}"


def write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))
    return path


def fake_fastpy(root: Path, version: str = "0.3.0") -> Path:
    """A fastpy checkout as far as the script looks at one."""
    fastpy = root / "fastpy"
    write(fastpy / "compiler" / "__init__.py", '"""fake fastpy"""\n')
    write(fastpy / "compiler" / "__main__.py", "def main():\n    return 0\n")
    write(fastpy / "compiler" / "codegen.py", "X = 1\n")
    # Not a source: a cache the checkout happens to hold.
    write(fastpy / "compiler" / "__pycache__" / "codegen.cpython-314.pyc", "junk")
    write(fastpy / "pyproject.toml", f'[project]\nname = "fastpy"\nversion = "{version}"\n')
    return fastpy


def fake_llvmlite(root: Path, version: str = "0.47.0") -> Path:
    """An installed llvmlite: the pure half, the binding, and its tests."""
    pkg = root / "site-packages" / "llvmlite"
    write(pkg / "__init__.py", "from ._version import get_versions\n")
    write(pkg / "_version.py",
          "# This file was generated by 'versioneer.py' (0.14)\n\n"
          f"version_version = '{version}'\n"
          "version_full = 'abc'\n"
          "def get_versions(default={}, verbose=False):\n"
          "    return {'version': version_version, 'full': version_full}\n")
    write(pkg / "utils.py", "import os\n")
    write(pkg / "ir" / "__init__.py", "from .types import *\n")
    write(pkg / "ir" / "types.py", "class Type:\n    pass\n")
    write(pkg / "binding" / "__init__.py", "import ctypes\n")
    write(pkg / "binding" / "ffi.py", "import ctypes\n")
    write(pkg / "tests" / "test_ir.py", "pass\n")
    return pkg


def fake_toolchain() -> types.ModuleType:
    """Stands in for fastpy's toolchain: writes the archive it is asked for."""
    module = types.ModuleType("fake_toolchain")

    def build_slateos_runtime_archive(dest):
        dest = Path(dest)
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(FAKE_ARCHIVE)
        return dest

    module.build_slateos_runtime_archive = build_slateos_runtime_archive
    return module


def files_under(directory: Path) -> list[str]:
    return sorted(p.relative_to(directory).as_posix()
                  for p in directory.rglob("*") if p.is_file())


def raises(fn, *args) -> str | None:
    """The `BundleError` text `fn(*args)` raises, or None if it returns."""
    try:
        fn(*args)
    except bundle.BundleError as err:
        return str(err)
    return None


