/// `format_struct`.
pub struct FormatStruct {
    /// The name `-o` takes.
    pub spec: &'static [u8],
    /// The default header.
    pub head: &'static [u8],
    /// How a value is printed.
    pub pr: Pr,
    /// What sorting by it sorts on.
    pub sr: Item,
    /// The default width.
    pub width: i32,
    /// Who invented it.
    pub vendor: i32,
    /// Justification and the `CF_*` flags.
    pub flags: u32,
}

