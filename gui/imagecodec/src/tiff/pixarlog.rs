//! PixarLog compression (32909): libtiff 4.7.1's `tif_pixarlog.c`, as its
//! RGBA reader drives it.
//!
//! Pixar's format for film frames: each sample an 11-bit code -- linear at
//! the bottom, logarithmic above -- the rows horizontally differenced, and
//! the strip deflated as one zlib stream. Asked for nothing in particular,
//! as the RGBA reader asks, the codec picks what to hand out from the
//! directory: 8-bit samples for `BitsPerSample` 8 and 16-bit ones for 16
//! (the other depths it knows, the reader has already refused), each code
//! through a table to its level. libtiff builds the tables with glibc's
//! `exp` and `log`; here they are the tables, as glibc made them.
//!
//! libtiff's quirks are kept:
//!
//! - its rows are the image's width even in a tile (`llen`), so a tile of
//!   another width is cut into rows that are not its own;
//! - with a number of samples a pixel other than 3 or 4, the accumulation
//!   hands out a row's second pixel as stored -- the encoder differences from
//!   the third on -- and adds the row's last sum into the next row's first
//!   pixel, which libtiff then shows;
//! - the codes are 16-bit values in the file's byte order, swapped as they
//!   are read, and nothing is swapped afterwards (`_TIFFNoPostDecode`); the
//!   horizontal predictor, which libtiff installs for PixarLog as for
//!   Deflate, runs over the output all the same.
//!
//! The inflating is the shared `deflate` crate's. zlib's rule -- inflate
//! until the buffer is full, still reading what needs no room: an end of
//! block, the next block's header and tables, the checksum after the last
//! block -- is kept at the buffer's end and for the checksum, which is read
//! where zlib reads it, after the Deflate data. But the crate decodes a
//! block at a time, so damage further into the block the strip ends in, or
//! further into the next block, is seen here and not by zlib; undamaged
//! files are not affected (`known-issues.md`; asked of lane A in
//! `requests/f-a-zlib-inflate-into-a-fixed-buffer-as-zlib-does.md`).

use alloc::vec;
use alloc::vec::Vec;

use super::dir::Directory;
use crate::{ImageError, ImageResult};

/// The 11 bits of a code (`CODE_MASK`).
const MASK: u32 = 0x7ff;

/// The codec's state (`PixarLogState`) for what the RGBA reader asks of it.
pub(super) struct PixarLog {
    /// Samples a pixel in a row: all of them held together, or 1 apart.
    stride: usize,
    /// `PIXARLOGDATAFMT_8BIT` rather than `PIXARLOGDATAFMT_16BIT`.
    eight_bit: bool,
    /// The translation buffer's bytes (`tbuf_size`).
    tbuf_bytes: usize,
}

/// `PixarLogSetupDecode`: `None` where libtiff's setup fails.
pub(super) fn setup(dir: &Directory, max_bytes: usize) -> Option<PixarLog> {
    let strip_height = dir.rows_per_strip.min(dir.length);
    let stride = if dir.planar_config == 1 {
        dir.samples_per_pixel
    } else {
        1
    };
    // `multiply_ms` and `add_ms`: 0 for a factor of 0 or for overflow, and
    // then no translation buffer, and no setup.
    let product = |a: u64, b: u64| {
        a.checked_mul(b)
            .filter(|&p| a != 0 && b != 0 && i64::try_from(p).is_ok())
    };
    let size = product(u64::from(stride), u64::from(dir.width))
        .and_then(|n| product(n, u64::from(strip_height)))
        .and_then(|n| product(n, 2))?;
    // One more pixel, "in case input ends mid-stride".
    let size = size
        .checked_add(u64::from(stride).checked_mul(2)?)
        .filter(|&n| i64::try_from(n).is_ok())?;
    let tbuf_bytes = usize::try_from(size).ok()?;
    // Its `malloc`, held to the decode's limit.
    if tbuf_bytes > max_bytes {
        return None;
    }
    // `PixarLogGuessDataFmt`, as far as the RGBA reader lets it get: its
    // depths are 8 and 16, with samples unsigned or of no stated kind.
    let eight_bit = match (dir.bits_per_sample, dir.sample_format) {
        (8, 1 | 4) => true,
        (16, 1 | 4) => false,
        _ => return None,
    };
    Some(PixarLog {
        stride: usize::from(stride),
        eight_bit,
        tbuf_bytes,
    })
}

impl PixarLog {
    /// `PixarLogDecode`: strip (or tile) `raw` into `out`, for an image
    /// `width` wide in a file of the given byte order.
    pub(super) fn decode(
        &self,
        raw: &[u8],
        out: &mut [u8],
        width: u32,
        big_endian: bool,
        max_bytes: usize,
    ) -> ImageResult<()> {
        let bad = ImageError::Corrupt("TIFF PixarLog data");
        let nsamples = if self.eight_bit {
            out.len()
        } else {
            out.len() / 2
        };
        // zlib's `avail_out` is 32 bits, and must fit the translation buffer.
        let bytes = nsamples
            .checked_mul(2)
            .filter(|&b| u32::try_from(b).is_ok() && b <= self.tbuf_bytes)
            .ok_or(bad.clone())?;
        let mut codes = vec![0u8; bytes];
        inflate(raw, &mut codes, max_bytes)?;
        // The codes, in the file's byte order, and one pixel of slack after
        // them, which the last row's stray sum lands in.
        let mut tbuf: Vec<u16> = codes
            .chunks_exact(2)
            .map(|pair| {
                let pair = [
                    pair.first().copied().unwrap_or(0),
                    pair.get(1).copied().unwrap_or(0),
                ];
                if big_endian {
                    u16::from_be_bytes(pair)
                } else {
                    u16::from_le_bytes(pair)
                }
            })
            .collect();
        tbuf.resize(nsamples.saturating_add(self.stride), 0);
        // A row is the image's width, tile or not; what does not make a
        // whole row is left out ("data truncated").
        let llen = usize::try_from(width)
            .ok()
            .and_then(|w| w.checked_mul(self.stride))
            .filter(|&n| n != 0)
            .ok_or(bad)?;
        let rows = nsamples.checked_div(llen).unwrap_or(0);
        for r in 0..rows {
            let at = r.saturating_mul(llen);
            let Some(row) = tbuf.get_mut(at..) else {
                break;
            };
            if self.eight_bit {
                accumulate(row, llen, self.stride, |i, code| {
                    if let Some(slot) = out.get_mut(at.saturating_add(i)) {
                        *slot = TO_LINEAR8.get(code).copied().unwrap_or(0);
                    }
                });
            } else {
                accumulate(row, llen, self.stride, |i, code| {
                    let level = TO_LINEAR16.get(code).copied().unwrap_or(0);
                    let o = at.saturating_add(i).saturating_mul(2);
                    // `uint16_t` in this machine's order, as the reader
                    // takes 16-bit samples.
                    if let Some(slot) = out.get_mut(o..o.saturating_add(2)) {
                        slot.copy_from_slice(&level.to_le_bytes());
                    }
                });
            }
        }
        Ok(())
    }
}

/// `horizontalAccumulate8` and `horizontalAccumulate16`: a row of `n` codes
/// undifferenced, each handed to `put` with its sample's index. `w` runs on
/// past the row, into the next row and the buffer's slack, as libtiff's
/// does -- for 3 and 4 samples a pixel each channel keeps a running sum;
/// for any other number, the running sums are kept in the buffer itself,
/// one pixel ahead, and the row's last pixel adds into the one after it.
fn accumulate(w: &mut [u16], n: usize, stride: usize, mut put: impl FnMut(usize, usize)) {
    let code = |v: u32| usize::try_from(v & MASK).unwrap_or(0);
    if n < stride {
        return;
    }
    if stride == 3 || stride == 4 {
        let mut sums = [0u32; 4];
        for (c, sum) in sums.iter_mut().enumerate().take(stride) {
            *sum = u32::from(w.get(c).copied().unwrap_or(0)) & MASK;
            put(c, code(*sum));
        }
        let mut i = stride;
        while i < n {
            for (c, sum) in sums.iter_mut().enumerate().take(stride) {
                let at = i.saturating_add(c);
                *sum = sum.wrapping_add(u32::from(w.get(at).copied().unwrap_or(0)));
                put(at, code(*sum));
            }
            i = i.saturating_add(stride);
        }
        return;
    }
    for c in 0..stride {
        put(c, code(u32::from(w.get(c).copied().unwrap_or(0))));
    }
    let mut p = stride;
    let mut left = n.saturating_sub(stride);
    while left > 0 {
        for _ in 0..stride {
            // `wp[stride] += *wp`, then `*op = table[*wp & mask]`.
            let v = w.get(p).copied().unwrap_or(0);
            if let Some(next) = w.get_mut(p.saturating_add(stride)) {
                *next = next.wrapping_add(v);
            }
            put(p, code(u32::from(v)));
            p = p.saturating_add(1);
        }
        left = left.saturating_sub(stride);
    }
}

/// zlib's `inflate` of strip `raw` into `out` until `out` is full, as
/// `PixarLogDecode` runs it.
fn inflate(raw: &[u8], out: &mut [u8], max_bytes: usize) -> ImageResult<()> {
    let bad = ImageError::Corrupt("TIFF PixarLog data");
    // The header, as `inflate` checks it: FCHECK, the method, a window of
    // at most 32 KiB (`inflateInit`'s), and no preset dictionary. Fewer
    // than two bytes is no progress at all (`Z_BUF_ERROR`).
    let Some((&[cmf, flg], body)) = raw.split_first_chunk::<2>() else {
        return Err(bad);
    };
    if u16::from_be_bytes([cmf, flg]) % 31 != 0
        || cmf & 0x0f != 8
        || cmf >> 4 > 7
        || flg & 0x20 != 0
    {
        return Err(bad);
    }
    // A block may run on past what the strip needs; zlib does not care how
    // far, and the crate's cap is only there to bound its buffer.
    let mut stream = deflate::inflate_stream(body, out.len().saturating_add(max_bytes));
    let mut filled = 0usize;
    while filled < out.len() {
        let rest = out.get_mut(filled..).ok_or(bad.clone())?;
        match stream.read(rest) {
            // The stream ended with room left: "Not enough data" (its
            // checksum, good or bad, changes nothing).
            Ok(0) => {
                return Err(ImageError::Corrupt(
                    "TIFF PixarLog data ends before the strip",
                ));
            }
            Ok(n) => filled = filled.saturating_add(n),
            Err(_) => return Err(bad),
        }
    }
    // Full. zlib reads on through what needs no room; where the last block
    // ends just here, that is the checksum after it.
    let mut probe = [0u8; 1];
    match stream.read(&mut probe) {
        Ok(0) => check_trailer(body, out, max_bytes),
        Ok(_) | Err(deflate::Error::OutputTooLarge) => Ok(()),
        Err(_) => Err(bad),
    }
}

/// The Adler-32 zlib reads straight after the Deflate data, whose end is
/// where `body` begins to decode completely: an error only if all four of
/// its bytes are there and are not `out`'s checksum.
fn check_trailer(body: &[u8], out: &[u8], max_bytes: usize) -> ImageResult<()> {
    let want = deflate::adler32(out).to_be_bytes();
    // Almost always the checksum ends the strip.
    if body.ends_with(&want) {
        return Ok(());
    }
    // Otherwise find where the Deflate data ends: the shortest prefix that
    // decodes completely (the crate reads bit by bit, so needs no more).
    let limit = out.len().saturating_add(max_bytes);
    let decodes = |len: usize| {
        body.get(..len)
            .is_some_and(|prefix| deflate::inflate_limited(prefix, limit).is_ok())
    };
    let (mut lo, mut hi) = (0usize, body.len());
    while lo < hi {
        let mid = lo.saturating_add(hi.saturating_sub(lo) / 2);
        if decodes(mid) {
            hi = mid;
        } else {
            lo = mid.saturating_add(1);
        }
    }
    match body.get(lo..lo.saturating_add(4)) {
        Some(stored) if stored.len() == 4 && stored != want => {
            Err(ImageError::Corrupt("TIFF PixarLog checksum"))
        }
        _ => Ok(()),
    }
}

