/// `search_format_array`.
#[must_use]
pub fn search_format(spec: &[u8]) -> Option<&'static FormatStruct> {
    FORMATS
        .binary_search_by(|f| f.spec.cmp(spec))
        .ok()
        .and_then(|i| FORMATS.get(i))
}

/// `search_macro_array`: a macro's column list.
#[must_use]
pub fn search_macro(spec: &[u8]) -> Option<&'static [u8]> {
    MACROS
        .binary_search_by(|(name, _)| (*name).cmp(spec))
        .ok()
        .and_then(|i| MACROS.get(i))
        .map(|(_, head)| *head)
}

/// `search_aix_array`: the specifier and header for `%c`, the table's own
/// `~` sentinel excluded.
#[must_use]
pub fn search_aix(c: u8) -> Option<(&'static [u8], &'static [u8])> {
    AIX_TABLE
        .iter()
        .take_while(|(d, _, _)| *d != b'~')
        .find(|(d, _, _)| *d == c)
        .map(|(_, spec, head)| (*spec, *head))
}

/// `search_shortsort_array`.
#[must_use]
pub fn search_shortsort(c: u8) -> Option<&'static [u8]> {
    SHORTSORT
        .iter()
        .take_while(|(d, _)| *d != b'~')
        .find(|(d, _)| *d == c)
        .map(|(_, spec)| *spec)
}

