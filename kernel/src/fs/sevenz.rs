/// Boot self-test: the shim reaches the crate and refuses what is not a 7z
/// archive. The crate's own tests (run on the host, against 7-Zip's archives
/// and verdicts) are what hold the reader to 7-Zip.
///
/// # Errors
///
/// [`KernelError::InternalError`] on any failure.
pub fn self_test() -> KernelResult<()> {
    serial_println!("[7z] === self-test start ===");
    let fail = |what: &str| {
        serial_println!("[7z]   FAIL: {}", what);
        Err(KernelError::InternalError)
    };
    if !matches!(
        un7z(b"not a 7z archive at all, not even close"),
        Err(KernelError::CorruptedData)
    ) {
        return fail("non-7z data was not CorruptedData");
    }
    // The same signature, cut short after it: an archive that ends early.
    if !matches!(
        un7z(SAMPLE_LZMA2.get(..8).unwrap_or(&[])),
        Err(KernelError::CorruptedData)
    ) {
        return fail("a truncated archive was not CorruptedData");
    }
    // Two real archives: every entry, with its size; each file's CRC is the
    // crate's to verify, so a wrong byte would have failed the extraction.
    let want: [(&str, usize, bool); 5] = [
        ("a.txt", 300, false),
        ("dir", 0, true),
        ("b.bin", 40, false),
        ("c.bin", 240, false),
        ("e.txt", 0, false),
    ];
    for (label, archive) in [
        ("LZMA2", &SAMPLE_LZMA2[..]),
        ("BCJ+LZMA2", &SAMPLE_BCJ_LZMA2[..]),
    ] {
        let entries = match un7z(archive) {
            Ok(e) => e,
            Err(e) => {
                serial_println!("[7z]   FAIL: the {} sample: {:?}", label, e);
                return Err(KernelError::InternalError);
            }
        };
        let all_there = entries.len() == want.len()
            && want.iter().all(|(name, size, is_dir)| {
                entries.iter().any(|e| {
                    e.name.as_bytes() == name.as_bytes()
                        && e.data.len() == *size
                        && e.is_dir == *is_dir
                })
            });
        if !all_there {
            serial_println!(
                "[7z]   FAIL: the {} sample's {} entries are not a.txt, dir/, b.bin, c.bin, e.txt",
                label,
                entries.len()
            );
            return Err(KernelError::InternalError);
        }
    }
    serial_println!("[7z] === self-test passed ===");
    Ok(())
}
