//! 7-Zip archive extraction (read-only), through the `sevenz` crate.
//!
//! A shim. The work is lane E's `sevenz` crate: a port of 7-Zip's reader,
//! `no_std` + `alloc`, decoding through the `xz` and `bzip2` crates, held by
//! its tests to 7-Zip's own archives and verdicts. This module keeps the
//! kernel's names for it -- [`un7z`] and [`SevenZEntry`] -- as `compress.rs`
//! does for `deflate` (requests/e-a-the-sevenz-crate-is-ready-for-the-kernel-shim.md).
//!
//! It replaced, on 2026-10-07, a reader written here rather than ported,
//! which decoded LZMA and LZMA2 through the kernel's own `xz` decoder (which
//! returned damaged data as good) and supported neither the BCJ filters nor
//! encryption's refusal in 7-Zip's terms.

use crate::error::{KernelError, KernelResult};
use crate::fs::path::PathBuf;
use crate::serial_println;
use alloc::collections::BTreeMap;
use alloc::vec::Vec;

/// The most an archive may decompress to, across all its folders: 256 MiB, the
/// cap the kernel's decoders share.
const MAX_OUTPUT: usize = 256 * 1024 * 1024;

/// A file entry extracted from the archive.
pub struct SevenZEntry {
    /// File name, forward-slash separated.
    ///
    /// 7z stores names as UTF-16LE. They are converted with
    /// [`PathBuf::from_utf16`], which is WTF-8 and therefore lossless: an
    /// archive written on Windows may contain unpaired surrogates, which
    /// `String::from_utf16_lossy` would turn into U+FFFD, collapsing distinct
    /// members onto one name.
    pub name: PathBuf,
    /// File data (empty for directories).
    pub data: Vec<u8>,
    /// Whether this entry is a directory.
    pub is_dir: bool,
}

/// The kernel's error for a `sevenz` crate error:
/// [`KernelError::NotSupported`] for a method or feature the reader lacks and
/// for an encrypted archive (no password can be given here),
/// [`KernelError::FileTooLarge`] at the output cap, and
/// [`KernelError::CorruptedData`] for the rest -- not a 7z, cut short, a
/// damaged header, damaged data, a CRC that fails.
fn kernel_error(e: ::sevenz::Error) -> KernelError {
    match e {
        ::sevenz::Error::Unsupported | ::sevenz::Error::PasswordRequired => {
            KernelError::NotSupported
        }
        ::sevenz::Error::OutputTooLarge => KernelError::FileTooLarge,
        _ => KernelError::CorruptedData,
    }
}

/// Extract every file of a 7z archive: each entry's name, whether it is a
/// directory, and its data (empty for a directory or an empty file).
///
/// Each folder -- the unit 7z compresses together -- is decoded once, so a
/// solid archive costs one decode however many files it holds. Deletion
/// records ("anti" items, which mark a file an update removed) are not files
/// and are left out. The whole archive's output is capped at 256 MiB.
///
/// # Errors
///
/// The first error any part of the archive gives, in the kinds
/// [`kernel_error`] maps: one damaged file fails the extraction, as it did.
pub fn un7z(data: &[u8]) -> KernelResult<Vec<SevenZEntry>> {
    let archive = ::sevenz::Archive::open(data).map_err(kernel_error)?;
    let mut data_of: BTreeMap<usize, Vec<u8>> = BTreeMap::new();
    let mut budget = MAX_OUTPUT;
    for folder in 0..archive.num_folders() {
        let result = archive.read_folder(folder, budget).map_err(kernel_error)?;
        for (index, file) in result.files {
            let bytes = file.map_err(kernel_error)?;
            budget = budget.saturating_sub(bytes.len());
            data_of.insert(index, bytes);
        }
        if let Some(e) = result.error_after_files {
            return Err(kernel_error(e));
        }
    }
    let mut out = Vec::with_capacity(archive.len());
    for entry in archive.entries() {
        if entry.is_anti() {
            continue;
        }
        out.push(SevenZEntry {
            name: PathBuf::from_utf16(entry.name_utf16()),
            data: data_of.remove(&entry.index()).unwrap_or_default(),
            is_dir: entry.is_dir(),
        });
    }
    Ok(out)
}

