    /// The positional pass is one cluster behind itself: the first cluster is
    /// `isol` until a second one turns it into `init`.
    #[test]
    fn the_positional_forms_are_fixed_up_one_cluster_late() {
        let masks = [1u64 << 40, 1 << 41, 1 << 42, 1 << 43];
        let form = |g: &SubGlyph| masks.iter().position(|&m| g.mask & m != 0);
        let mut glyphs = run("\u{A98F}\u{A990}\u{A991}");
        let ranges = vec![
            (0usize, 1usize, Cluster::Standard),
            (1, 2, Cluster::Standard),
            (2, 3, Cluster::Standard),
        ];
        setup_topographical_masks(&mut glyphs, &ranges, masks);
        let forms: Vec<Option<usize>> = glyphs.iter().map(form).collect();
        assert_eq!(forms, vec![Some(INIT), Some(MEDI), Some(FINA)]);

        // One cluster alone stays isolated.
        let mut glyphs = run("\u{A98F}");
        setup_topographical_masks(&mut glyphs, &[(0, 1, Cluster::Standard)], masks);
        assert_eq!(glyphs.iter().map(form).collect::<Vec<_>>(), vec![Some(ISOL)]);
    }

    /// A non-cluster breaks the chain, so the cluster before it stays `isol`
    /// and the one after it starts a new word.
    #[test]
    fn a_non_cluster_breaks_the_positional_chain() {
        let masks = [1u64 << 40, 1 << 41, 1 << 42, 1 << 43];
        let form = |g: &SubGlyph| masks.iter().position(|&m| g.mask & m != 0);
        let mut glyphs = run("\u{A98F} \u{A990}");
        let ranges = vec![
            (0usize, 1usize, Cluster::Standard),
            (1, 2, Cluster::NonCluster),
            (2, 3, Cluster::Standard),
        ];
        setup_topographical_masks(&mut glyphs, &ranges, masks);
        let forms: Vec<Option<usize>> = glyphs.iter().map(form).collect();
        assert_eq!(forms, vec![Some(ISOL), None, Some(ISOL)]);
    }

    /// A face with none of the four features gets no pass at all — which is
