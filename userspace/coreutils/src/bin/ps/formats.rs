#[cfg(test)]
#[allow(clippy::unwrap_used, clippy::indexing_slicing)]
mod tests {
    use super::*;

    #[test]
    fn every_specifier_is_found_by_its_name() {
        for f in FORMATS {
            assert!(std::ptr::eq(search_format(f.spec).unwrap(), f));
        }
        assert!(search_format(b"nosuch").is_none());
        assert_eq!(search_macro(b"DefSysV"), Some(&b"pid,tname,time,cmd"[..]));
        assert!(search_macro(b"pid").is_none());
    }

    #[test]
    fn the_tables_are_in_strcmp_order() {
        assert!(FORMATS.windows(2).all(|w| w[0].spec < w[1].spec));
        assert!(MACROS.windows(2).all(|w| w[0].0 < w[1].0));
    }

    #[test]
    fn aix_and_short_sort_letters() {
        assert_eq!(search_aix(b'p'), Some((&b"pid"[..], &b"PID"[..])));
        assert_eq!(search_aix(b'~'), None);
        assert_eq!(search_shortsort(b'P'), Some(&b"ppid"[..]));
        assert_eq!(search_shortsort(b'K'), None);
    }
}
