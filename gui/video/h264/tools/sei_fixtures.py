"""Write src/sei/tests/fixtures.rs: real SEI units, and what FFmpeg reads in them.

For each of a few of FFmpeg's FATE H.264 samples this takes the first
sequence parameter set and the first SEI unit as they are in the file --
escapes and all -- and every syntax element FFmpeg's `trace_headers`
bitstream filter prints for that SEI, and writes them out as Rust
constants. src/sei/tests.rs reads the SEI against the SPS and checks what it
reads against the trace.

    python gui/video/h264/tools/sei_fixtures.py <fate-suite>/h264

`ffmpeg` and `rustfmt` must be on PATH.
"""
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "src" / "sei" / "tests" / "fixtures.rs"

# (constant name, file, what it exercises)
FIXTURES = [
    ("RECOVERY", "intra_refresh.h264", "a recovery point"),
    ("FRAME_PACKING", "frame-packing-temporal.h264", "a frame packing arrangement"),
    ("MANY", "sei-1.h264",
     "a buffering period, picture timing, display orientation, a mastering display"),
    ("X264", "crew_cif.nal", "x264's user data"),
    ("BROADCAST", "bbc2.sample.h264",
     "a buffering period, picture timing, a recovery point, registered user data"),
]


def units(data: bytes):
    """Annex B units as they are in the file, start codes and trailing zero
    bytes off, escapes kept."""
    starts = []
    i = 0
    while (j := data.find(b"\x00\x00\x01", i)) >= 0:
        starts.append(j + 3)
        i = j + 3
    for k, s in enumerate(starts):
        e = starts[k + 1] - 3 if k + 1 < len(starts) else len(data)
        unit = data[s:e]
        while unit.endswith(b"\x00"):
            unit = unit[:-1]
        yield unit


def first(data: bytes, kind: int) -> bytes:
    for u in units(data):
        if u and u[0] & 0x1F == kind:
            return u
    raise SystemExit(f"no unit of type {kind}")


def trace(path: Path) -> list:
    """The first SEI unit's syntax elements, in order."""
    out = subprocess.run(
        ["ffmpeg", "-hide_banner", "-i", str(path), "-c", "copy", "-bsf:v", "trace_headers",
         "-frames:v", "1", "-f", "null", "-"],
        capture_output=True, text=True, encoding="utf-8", errors="replace", check=False,
    ).stderr
    fields = None
    for line in out.splitlines():
        if "Supplemental Enhancement Information" in line:
            if fields is not None:
                break
            fields = []
            continue
        if fields is None:
            continue
        if "] " in line and any(s in line for s in (
                "Slice", "Packet:", "Extradata", "Parameter Set", "Access Unit")):
            break
        parts = line.split()
        if len(parts) >= 6 and parts[-2] == "=":
            fields.append((parts[4], int(parts[-1])))
    if fields is None:
        raise SystemExit(f"{path}: no SEI traced")
    return fields


def rust_bytes(b: bytes) -> str:
    return "[" + ", ".join(f"0x{x:02X}" for x in b) + "]"


def rust_fields(fields) -> str:
    return "[" + ", ".join(f'("{n}", {v})' for n, v in fields) + "]"


def main() -> None:
    root = Path(sys.argv[1])
    body = [
        "// Generated by tools/sei_fixtures.py from FFmpeg's FATE H.264 samples,",
        "// and FFmpeg's trace_headers reading of them. Do not edit.",
        "",
        "/// One sample's first SPS and SEI unit, and the trace of the SEI.",
        "pub(super) struct Fixture {",
        "    pub(super) name: &'static str,",
        "    pub(super) sps: &'static [u8],",
        "    pub(super) sei: &'static [u8],",
        "    pub(super) trace: &'static [(&'static str, i64)],",
        "}",
        "",
    ]
    names = []
    for const, file, what in FIXTURES:
        path = root / file
        data = path.read_bytes()
        body += [
            f"/// {file}: {what}.",
            f"pub(super) const {const}: Fixture = Fixture {{",
            f'    name: "{file}",',
            f"    sps: &{rust_bytes(first(data, 7))},",
            f"    sei: &{rust_bytes(first(data, 6))},",
            f"    trace: &{rust_fields(trace(path))},",
            "};",
            "",
        ]
        names.append(const)
    body += [
        "/// Every fixture.",
        f"pub(super) const ALL: [Fixture; {len(names)}] = [{', '.join(names)}];",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(body), encoding="utf-8", newline="\n")
    subprocess.run(["rustfmt", "--edition", "2024", str(OUT)], check=True)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
