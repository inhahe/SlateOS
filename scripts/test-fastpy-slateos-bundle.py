def test_a_named_checkout_is_used_and_a_wrong_one_refused():
    with tempfile.TemporaryDirectory() as tmp:
        fastpy = fake_fastpy(Path(tmp))
        check("--fastpy names the checkout", bundle.find_fastpy(str(fastpy)), fastpy)
        wrong = Path(tmp) / "not-fastpy"
        wrong.mkdir()
        err = raises(bundle.find_fastpy, str(wrong))
        check("a named directory without compiler/ is refused, not fallen through",
              err is not None and "compiler/__init__.py" in err, True)


def test_fastpy_dir_is_honoured_like_the_fixture_builder():
    with tempfile.TemporaryDirectory() as tmp:
        fastpy = fake_fastpy(Path(tmp))
        saved = os.environ.get("FASTPY_DIR")
        os.environ["FASTPY_DIR"] = str(fastpy)
        try:
            check("$FASTPY_DIR is the checkout when --fastpy is absent",
                  bundle.find_fastpy(None), fastpy)
            os.environ["FASTPY_DIR"] = str(Path(tmp) / "missing")
            check("a wrong $FASTPY_DIR is an error too",
                  raises(bundle.find_fastpy, None) is not None, True)
        finally:
            if saved is None:
                os.environ.pop("FASTPY_DIR", None)
            else:
                os.environ["FASTPY_DIR"] = saved


def test_llvmlite_must_be_the_package_directory():
    with tempfile.TemporaryDirectory() as tmp:
        pkg = fake_llvmlite(Path(tmp))
        check("llvmlite's package directory is accepted",
              bundle.find_llvmlite(str(pkg)), pkg)
        err = raises(bundle.find_llvmlite, str(pkg.parent))
        check("its parent is not -- it has no ir/__init__.py",
              err is not None and "ir/__init__.py" in err, True)


def test_llvmlite_version_is_read_without_importing_it():
    with tempfile.TemporaryDirectory() as tmp:
        pkg = fake_llvmlite(Path(tmp), version="0.47.0")
        check("versioneer's assignment is read", bundle.llvmlite_version(pkg), "0.47.0")
        write(pkg / "_version.py", "def get_versions():\n    return {}\n")
        check("no assignment reads as unknown, not as an error",
              bundle.llvmlite_version(pkg), "unknown")


def test_load_toolchain_wants_the_archive_builder():
    with tempfile.TemporaryDirectory() as tmp:
        fastpy = fake_fastpy(Path(tmp))
        write(fastpy / "compiler" / "toolchain.py", "SLATEOS_TARGET = 'x'\n")
        err = raises(bundle.load_toolchain, fastpy)
        check("a fastpy older than the archive builder is named as such",
              err is not None and "build_slateos_runtime_archive" in err, True)

        # A dataclass, as the real toolchain.py has: `dataclasses` looks the
        # defining module up in sys.modules while it builds the class, so a
        # module loaded by path and not registered fails right here.
        write(fastpy / "compiler" / "toolchain.py",
              "from __future__ import annotations\n"
              "from dataclasses import dataclass\n"
              "WHICH = 'the chosen checkout'\n"
              "@dataclass\n"
              "class PythonInstall:\n"
              "    version: tuple[int, int]\n"
              "def build_slateos_runtime_archive(dest):\n    return dest\n")
        before = set(sys.modules)
        module = bundle.load_toolchain(fastpy)
        check("the chosen checkout's toolchain is the one loaded",
              getattr(module, "WHICH", None), "the chosen checkout")
        check("its dataclasses build",
              module.PythonInstall((3, 12)).version, (3, 12))
        check("loading it binds no `compiler` package in sys.modules",
              sorted(name for name in set(sys.modules) - before
                     if name == "compiler" or name.startswith("compiler.")), [])


