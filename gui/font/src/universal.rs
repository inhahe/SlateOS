    /// A broken cluster gains a dotted circle; a well-formed one does not.
    #[test]
    fn a_broken_cluster_gains_a_dotted_circle() {
        let mut glyphs = run("\u{A9B6}");
        let mut ranges = Vec::new();
        clusters(&glyphs, &mut ranges);
        assert_eq!(ranges, vec![(0, 1, Cluster::Broken)]);
        syllabic::stamp(&mut glyphs, &ranges, Cluster::code);
        reorder(&mut glyphs, Some(99));
        assert_eq!(glyphs.len(), 2);
        assert_eq!(order(&glyphs), vec![99, 0]);
        assert_eq!(glyphs[0].universal.category, Category::Base);
        assert_eq!(glyphs[0].cluster, glyphs[1].cluster);

        let mut glyphs = run("\u{A98F}\u{A9B6}");
        let mut ranges = Vec::new();
        clusters(&glyphs, &mut ranges);
        syllabic::stamp(&mut glyphs, &ranges, Cluster::code);
        reorder(&mut glyphs, Some(99));
        assert_eq!(glyphs.len(), 2, "nothing to fix");
    }

    /// The circle goes *after* a repha, which is drawn above the letter that
    /// follows it and so needs a letter to follow.
    ///
    /// Reading that off the output takes a cluster of this shape and no
    /// shorter, because the repha's own forward move runs straight afterwards
    /// and hides the difference in every simpler one: in `repha + circle +
    /// post-base` the repha hops the circle and lands exactly where inserting
    /// the circle in front of it would have put things. Here it hops *three*
    /// glyphs, so the two orders come out different — `[circle, 1, 2, repha,
    /// 3]` if the circle went after the repha, `[circle, repha, 1, 2, 3]` if it
    /// went before.
    #[test]
    fn the_circle_goes_after_a_repha() {
        let mut glyphs = run("\u{A98F}\u{A98F}\u{A98F}\u{A9B6}");
        glyphs[0].universal.category = Category::Repha;
        let ranges = vec![(0usize, 4usize, Cluster::Broken)];
        syllabic::stamp(&mut glyphs, &ranges, Cluster::code);
        reorder(&mut glyphs, Some(99));
        assert_eq!(order(&glyphs), vec![99, 1, 2, 0, 3]);
    }

    /// A face with no U+25CC gets no circle, which is the honest answer: there
